/**
 * Кодекс: раздел космических кораблей.
 *
 * Отдельный тип записей `ship` с подтипами (в поле `group`, с префиксом
 * «Корабль · …»): достоинства (усовершенствования), модули, орудия, торпеды и
 * мины, изъяны, верфи, классы и типы кораблей. Данные извлечены из ST3001
 * «Кориолис», гл. 7 (стр. 142–162): табл. 7.4 (типы), 7.5–6 (базовые
 * характеристики классов), 7.7 (модули), 7.8–9 (орудия), 7.10
 * (усовершенствования), а также изъяны и верфи.
 */

import type { CodexEntry, CodexStat, TechLevel } from "./codex";

const slugged = new Set<string>();
function shipId(name: string): string {
  const base = `ship:${name}`.toLowerCase().replace(/\s+/g, "-").replace(/[^a-zа-я0-9:-]/gi, "");
  let key = base;
  let n = 2;
  while (slugged.has(key)) key = `${base}-${n++}`;
  slugged.add(key);
  return key;
}

interface ShipRow {
  name: string;
  group: string;
  summary: string;
  stats?: CodexStat[];
  tags?: string[];
  tech?: TechLevel;
  price?: string;
  licensed?: boolean;
}

function ship(r: ShipRow): CodexEntry {
  return {
    id: shipId(r.name),
    category: "ship",
    name: r.name,
    group: `Корабль · ${r.group}`,
    summary: r.summary,
    stats: r.stats,
    tags: r.tags,
    tech: r.tech,
    price: r.price,
    licensed: r.licensed,
  };
}

