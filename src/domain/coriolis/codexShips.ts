function shipStats(r: {
  cls: string;
  energy: string;
  hull: string;
  man: string;
  vis: string;
  armor: string;
  speed: string;
  slots?: string;
}): CodexStat[] {
  const s: CodexStat[] = [
    { label: "Класс", value: r.cls },
    { label: "Энергия", value: r.energy },
    { label: "Прочность", value: r.hull },
    { label: "Манёвр.", value: r.man },
    { label: "Заметность", value: r.vis },
    { label: "Броня", value: r.armor },
    { label: "Скорость", value: r.speed },
  ];
  if (r.slots) s.push({ label: "Отсеки", value: r.slots });
  return s;
}

