const slugged = new Set<string>();
function campId(prefix: string, name: string): string {
  const base = `${prefix}:${name}`.toLowerCase().replace(/\s+/g, "-").replace(/[^a-zа-я0-9:-]/gi, "");
  let key = base;
  let n = 2;
  while (slugged.has(key)) key = `${base}-${n++}`;
  slugged.add(key);
  return key;
}

