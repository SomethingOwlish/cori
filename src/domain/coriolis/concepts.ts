/**
 * Амплуа персонажа и роли.
 *
 * Каждое амплуа разбито на три роли. Амплуа задаёт ключевую характеристику,
 * модификатор репутации, список достоинств на выбор, снаряжение, личные
 * проблемы, взаимоотношения, внешность и имена. Роль уточняет прошлое героя и
 * определяет его четыре КЛЮЧЕВЫХ навыка (в них при создании можно вложить до 3
 * пунктов; в остальные — максимум по 1).
 *
 * Источник: ST3001 «Кориолис», гл. 2, стр. 30–51.
 */

import type { AttributeKey } from "./attributes";
import type { SkillKey } from "./skills";

export type ConceptKey =
  | "artist"
  | "dataSpider"
  | "fugitive"
  | "merchant"
  | "operative"
  | "pilot"
  | "preacher"
  | "scientist"
  | "sailor"
  | "soldier"
  | "pioneer";

export interface RoleDef {
  key: string;
  name: string;
  /** Четыре ключевых навыка роли. */
  keySkills: SkillKey[];
  /** Пояснение роли. */
  description: string;
}

/** Строка выбора снаряжения: два варианта, из которых берётся один. */
export type GearChoice = [string, string];

export interface ConceptDef {
  key: ConceptKey;
  name: string;
  /** Флейвор-описание амплуа. */
  description: string;
  /** Характеристика, которую можно поднять до 5. */
  keyAttribute: AttributeKey;
  /** Модификатор репутации (прибавляется к базе воспитания). */
  reputationModifier: number;
  roles: RoleDef[];
  /** Достоинства на выбор (одно личное). Ключи из `talents.ts`. */
  talentChoices: string[];
  /** Варианты внешности: черты лица. */
  appearanceFace: string[];
  /** Варианты внешности: одежда. */
  appearanceClothing: string[];
  /** Личные проблемы на выбор. */
  personalProblems: string[];
  /** Примеры взаимоотношений с другими персонажами игроков. */
  relationships: string[];
  /** Начальное снаряжение: по одному предмету из каждой строки. */
  gear: GearChoice[];
  /** Примеры имён. */
  names: string[];
}

