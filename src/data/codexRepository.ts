/**
 * Персистентность пользовательских записей кодекса — контракт хранилища.
 *
 * Встроенный каталог (`BUILTIN_CODEX`) статичен и живёт в коде; репозиторий
 * хранит только записи, которые добавили ведущий или игроки. Как и остальные
 * репозитории приложения, он не зависит от бэкенда: localStorage для локальной
 * игры и тестов, Firestore — для общей на всю кампанию.
 */

import type { CodexEntry } from "../domain/coriolis";

export interface CodexRepository {
  /** Возвращает все пользовательские записи. Порядок не гарантируется. */
  list(): Promise<CodexEntry[]>;

  /** Создаёт или заменяет запись (ключ — её `id`). */
  save(entry: CodexEntry): Promise<void>;

  /** Удаляет запись. Удаление отсутствующего id — no-op. */
  delete(id: string): Promise<void>;
}
